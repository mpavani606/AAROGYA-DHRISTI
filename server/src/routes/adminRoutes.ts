import { Router } from "express";
import { auth } from "../middleware/auth.js";
import { requireRole } from "../middleware/rbac.js";
import { audit } from "../middleware/audit.js";
import { auditAccess } from "../middleware/auditAccess.js";
import { auditLogs, assignDoctorHospitalProfile, ashaWorkerOptions, createAshaWorker, createHospital, createUser, createHospitalManager, deleteHospital, getDoctorDetails, getHospitalDetails, hospitalOverview, listAshaWorkers, listHospitals, listDoctors, listHospitalManagers, patchUserAssignment, resetHospitalManagerPassword, reviewDoctorVerification, setAshaWorkerStatus, setDoctorStatus, setHospitalManagerStatus, updateHospital } from "../controllers/adminController.js";
import { downloadDoctorDocument } from "../controllers/doctorController.js";
import { resetDemo } from "../controllers/demoResetController.js";
import rateLimit from "express-rate-limit";
import { validateMongoIdParams } from "../middleware/validate.js";

export const adminRoutes = Router();
const adminWriteLimit = rateLimit({ windowMs: 60_000, limit: 20, standardHeaders: true, legacyHeaders: false });
const resetLimit = rateLimit({ windowMs: 15 * 60_000, limit: 3, standardHeaders: true, legacyHeaders: false });
adminRoutes.use(auth, auditAccess, requireRole("system_admin", "district_admin"), validateMongoIdParams);
adminRoutes.get("/overview", requireRole("system_admin"), hospitalOverview);
adminRoutes.get("/hospitals", listHospitals);
adminRoutes.get("/hospitals/:hospitalId", getHospitalDetails);
adminRoutes.get("/doctors", listDoctors);
adminRoutes.get("/doctors/:userId", getDoctorDetails);
adminRoutes.get("/doctors/:userId/documents/:documentId", requireRole("system_admin"), downloadDoctorDocument);
adminRoutes.patch("/doctors/:userId/verification", requireRole("system_admin"), adminWriteLimit, reviewDoctorVerification);
adminRoutes.patch("/doctors/:userId/status", requireRole("system_admin"), adminWriteLimit, setDoctorStatus);
adminRoutes.post("/doctors/:userId/hospital-profile", requireRole("system_admin"), adminWriteLimit, assignDoctorHospitalProfile);
adminRoutes.post("/hospitals", requireRole("system_admin"), adminWriteLimit, audit("create", "hospital"), createHospital);
adminRoutes.patch("/hospitals/:hospitalId", requireRole("system_admin"), adminWriteLimit, audit("update", "hospital"), updateHospital);
adminRoutes.delete("/hospitals/:hospitalId", requireRole("system_admin"), adminWriteLimit, audit("delete", "hospital"), deleteHospital);
adminRoutes.post("/users", adminWriteLimit, audit("create", "user"), createUser);
adminRoutes.patch("/users/:userId/assignment", adminWriteLimit, audit("assign", "user"), patchUserAssignment);
adminRoutes.get("/asha-workers/options", requireRole("system_admin"), ashaWorkerOptions);
adminRoutes.get("/asha-workers", requireRole("system_admin"), listAshaWorkers);
adminRoutes.post("/asha-workers", requireRole("system_admin"), adminWriteLimit, createAshaWorker);
adminRoutes.patch("/asha-workers/:userId/status", requireRole("system_admin"), adminWriteLimit, setAshaWorkerStatus);
adminRoutes.get("/hospital-managers", requireRole("system_admin"), listHospitalManagers);
adminRoutes.post("/hospital-managers", requireRole("system_admin"), adminWriteLimit, createHospitalManager);
adminRoutes.patch("/hospital-managers/:userId/status", requireRole("system_admin"), adminWriteLimit, setHospitalManagerStatus);
adminRoutes.post("/hospital-managers/:userId/password-reset", requireRole("system_admin"), adminWriteLimit, resetHospitalManagerPassword);
adminRoutes.get("/audit-logs", requireRole("system_admin"), adminWriteLimit, auditLogs);
adminRoutes.post("/reset-demo", requireRole("system_admin"), resetLimit, resetDemo);
