import { Router } from "express";
import multer from "multer";
import { auth } from "../middleware/auth.js";
import { requireRole } from "../middleware/rbac.js";
import { requireDoctorVerification } from "../middleware/doctorVerification.js";
import { requirePatientCareRelationship } from "../middleware/patientCareRelationship.js";
import { auditAccess } from "../middleware/auditAccess.js";
import { validateMongoIdParams } from "../middleware/validate.js";
import rateLimit from "express-rate-limit";
import { createPatient, listPatients, getPatient, getOwnPatient, updatePatient, linkAbha, createConsent, getConsent, registerMember, issueToken, slip, extractAarogyasri, duplicateCheck } from "../controllers/patientController.js";
import { createOwnPrescription, createOwnRefillRequest, getOwnHealthSummary, getOwnHealthWorkers, getOwnMedicineAvailability, listOwnPrescriptions, listOwnRefillRequests, updateOwnPatientProfile } from "../controllers/patientDashboardController.js";
export const patientRoutes = Router();
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 5 * 1024 * 1024 }, fileFilter: (_req, file, cb) => cb(null, /^(image\/|application\/pdf$)/.test(file.mimetype)) });
const registrationLimit = rateLimit({ windowMs: 60_000, limit: 15, standardHeaders: true, legacyHeaders: false });
patientRoutes.use(auth, auditAccess, requireRole("patient", "doctor", "district_admin", "system_admin", "asha_worker"), requireDoctorVerification, validateMongoIdParams);
patientRoutes.post("/", requireRole("doctor", "district_admin", "system_admin", "asha_worker"), registrationLimit, createPatient);
patientRoutes.post("/duplicate-check", requireRole("doctor", "district_admin", "system_admin"), registrationLimit, duplicateCheck);
patientRoutes.post("/aarogyasri/extract", requireRole("doctor", "district_admin", "system_admin"), registrationLimit, upload.single("file"), extractAarogyasri);
patientRoutes.get("/", listPatients);
patientRoutes.get("/me", getOwnPatient);
patientRoutes.get("/me/health-summary", requireRole("patient"), getOwnHealthSummary);
patientRoutes.get("/me/health-workers", requireRole("patient"), getOwnHealthWorkers);
patientRoutes.patch("/me", requireRole("patient"), updateOwnPatientProfile);
patientRoutes.get("/me/refills", requireRole("patient"), listOwnRefillRequests);
patientRoutes.post("/me/refills", requireRole("patient"), createOwnRefillRequest);
patientRoutes.get("/me/prescriptions", requireRole("patient"), listOwnPrescriptions);
patientRoutes.post("/me/prescriptions", requireRole("patient"), createOwnPrescription);
patientRoutes.get("/me/medicine-availability", requireRole("patient"), getOwnMedicineAvailability);
patientRoutes.get("/:patientId", requirePatientCareRelationship, getPatient);
patientRoutes.patch("/:patientId", requirePatientCareRelationship, updatePatient);
patientRoutes.post("/:patientId/abha", requirePatientCareRelationship, linkAbha);
patientRoutes.post("/:patientId/abha/link", requirePatientCareRelationship, linkAbha);
patientRoutes.post("/:patientId/consents", requirePatientCareRelationship, createConsent);
patientRoutes.get("/:patientId/consents/:purpose", requirePatientCareRelationship, getConsent);
patientRoutes.post("/:patientId/family", requirePatientCareRelationship, registerMember);
patientRoutes.post("/:patientId/token", requirePatientCareRelationship, issueToken);
patientRoutes.post("/:patientId/tokens", requirePatientCareRelationship, issueToken);
patientRoutes.get("/:patientId/slip", requirePatientCareRelationship, slip);
patientRoutes.post("/:patientId/aarogyasri/extract", requireRole("doctor", "district_admin", "system_admin"), requirePatientCareRelationship, upload.single("file"), extractAarogyasri);
patientRoutes.post("/:patientId/imaging", requirePatientCareRelationship, (_req, res) => res.status(202).json({ accepted: true }));
