import { Router } from "express";
import multer from "multer";
import { auth } from "../middleware/auth.js";
import { requireRole } from "../middleware/rbac.js";
import { requireDoctorVerification } from "../middleware/doctorVerification.js";
import { auditAccess } from "../middleware/auditAccess.js";
import { requirePatientCareRelationship } from "../middleware/patientCareRelationship.js";
import { requireCaseCareRelationship } from "../middleware/caseCareRelationship.js";
import { requirePatientScreeningConsent, requireActiveScreeningConsent } from "../middleware/consent.js";
import rateLimit from "express-rate-limit";
import { validateMongoIdParams } from "../middleware/validate.js";
import { createCase, addCaseImage, caseImages, caseImage, caseScreeningReport, aiQualityCheck, aiInfer, aiHistory, aiModels, addHabit, addSymptom, caseRiskScore, createPlan, listPlans, updatePlan, deletePlan } from "../controllers/phase6Controller.js";

const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 10 * 1024 * 1024 }, fileFilter: (_req, file, cb) => cb(null, ["image/jpeg", "image/png"].includes(file.mimetype)) });
export const phase6Routes = Router();
phase6Routes.use(auth, requireRole("patient", "doctor", "district_admin", "system_admin"), requireDoctorVerification, auditAccess, validateMongoIdParams);
const imageLimit = rateLimit({ windowMs: 60_000, limit: 10, standardHeaders: true, legacyHeaders: false });
const aiLimit = rateLimit({ windowMs: 60_000, limit: 6, standardHeaders: true, legacyHeaders: false });
phase6Routes.post("/cases", requirePatientCareRelationship, requireActiveScreeningConsent, createCase);
phase6Routes.get("/cases/:id/images", requireCaseCareRelationship, requireActiveScreeningConsent, caseImages);
phase6Routes.get("/cases/:id/images/:imageId", requireCaseCareRelationship, requireActiveScreeningConsent, caseImage);
phase6Routes.get("/cases/:id/screening-report", requireCaseCareRelationship, requireActiveScreeningConsent, requirePatientScreeningConsent, caseScreeningReport);
phase6Routes.post("/cases/:id/images", requireCaseCareRelationship, requireActiveScreeningConsent, requirePatientScreeningConsent, imageLimit, upload.single("image"), addCaseImage);
phase6Routes.post("/ai/quality-check", aiLimit, upload.single("image"), requirePatientCareRelationship, requireActiveScreeningConsent, aiQualityCheck);
phase6Routes.post("/ai/infer", requireCaseCareRelationship, requireActiveScreeningConsent, requirePatientScreeningConsent, aiLimit, upload.single("image"), aiInfer);
phase6Routes.get("/cases/:id/ai-history", requireCaseCareRelationship, requireActiveScreeningConsent, requirePatientScreeningConsent, aiHistory);
phase6Routes.get("/ai/models", aiModels);
phase6Routes.post("/patients/:id/habits", requirePatientCareRelationship, requireActiveScreeningConsent, addHabit);
phase6Routes.post("/patients/:id/symptoms", requirePatientCareRelationship, requireActiveScreeningConsent, addSymptom);
phase6Routes.post("/cases/:id/risk-score", requireCaseCareRelationship, requireActiveScreeningConsent, caseRiskScore);
phase6Routes.post("/patients/:id/cessation-plans", requirePatientCareRelationship, createPlan);
phase6Routes.get("/patients/:id/cessation-plans", requirePatientCareRelationship, listPlans);
phase6Routes.patch("/patients/:id/cessation-plans/:planId", requirePatientCareRelationship, updatePlan);
phase6Routes.delete("/patients/:id/cessation-plans/:planId", requirePatientCareRelationship, deletePlan);
