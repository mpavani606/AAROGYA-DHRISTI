import { Router } from "express";
import { auth } from "../middleware/auth.js";
import { requireRole } from "../middleware/rbac.js";
import { requireDoctorVerification } from "../middleware/doctorVerification.js";
import { auditAccess } from "../middleware/auditAccess.js";
import rateLimit from "express-rate-limit";
import { requirePatientCareRelationship } from "../middleware/patientCareRelationship.js";
import { requireAppointmentCareRelationship } from "../middleware/appointmentCareRelationship.js";
import { requireCaseCareRelationship } from "../middleware/caseCareRelationship.js";
import { requireNavigatorTaskCareRelationship } from "../middleware/navigatorTaskCareRelationship.js";
import { validateMongoIdParams } from "../middleware/validate.js";
import { doctorSlots, availableDoctors, listAppointments, createAppointment, createOwnAppointment, updateAppointment, confirmAppointment, attendance, createVideoRoom, videoToken, directions, appointmentSlip, requestLocation, shareLocation, caseLocation, navigatorTasks, contactAttempt, transportRequest, notifications, markNotificationRead } from "../controllers/phase8Controller.js";

export const phase8Routes = Router();
phase8Routes.post("/location/share", rateLimit({ windowMs: 15 * 60_000, limit: 5, standardHeaders: true, legacyHeaders: false }), auditAccess, shareLocation);
phase8Routes.use(auth, requireRole("patient", "doctor", "district_admin", "system_admin"), requireDoctorVerification, auditAccess, validateMongoIdParams);
phase8Routes.get("/doctors/available", requireRole("patient"), availableDoctors);
phase8Routes.get("/doctors/:id/slots", doctorSlots);
phase8Routes.get("/appointments", listAppointments);
phase8Routes.post("/appointments/me", requireRole("patient"), createOwnAppointment);
phase8Routes.post("/appointments", requirePatientCareRelationship, createAppointment);
phase8Routes.patch("/appointments/:id", requireAppointmentCareRelationship, updateAppointment);
phase8Routes.post("/appointments/:id/confirm", requireRole("doctor"), requireAppointmentCareRelationship, confirmAppointment);
phase8Routes.post("/appointments/:id/attendance", requireAppointmentCareRelationship, attendance);
phase8Routes.get("/appointments/:id/directions", requireAppointmentCareRelationship, directions);
phase8Routes.get("/appointments/:id/slip", requireAppointmentCareRelationship, appointmentSlip);
phase8Routes.post("/video/rooms", requireAppointmentCareRelationship, createVideoRoom);
phase8Routes.get("/video/rooms/:id/token", requireAppointmentCareRelationship, videoToken);
phase8Routes.post("/location/request/:id", requirePatientCareRelationship, requestLocation);
phase8Routes.post("/location/request", requirePatientCareRelationship, requestLocation);
phase8Routes.get("/cases/:id/location", requireRole("doctor"), requireCaseCareRelationship, caseLocation);
phase8Routes.get("/navigator/tasks", requireRole("doctor"), navigatorTasks);
phase8Routes.post("/navigator/tasks/:id/contact-attempt", requireRole("doctor"), requireNavigatorTaskCareRelationship, contactAttempt);
phase8Routes.post("/navigator/tasks/:id/transport", requireRole("doctor"), requireNavigatorTaskCareRelationship, transportRequest);
phase8Routes.get("/notifications", notifications);
phase8Routes.patch("/notifications/:id/read", markNotificationRead);
